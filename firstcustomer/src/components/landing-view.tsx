export function LandingView(props: {
  content: PageContent;
  claims: { text: string }[];
  productName: string;
  productUrl: string | null;
  slug: string;
  submitted?: boolean;
  simulated?: boolean;
  formAction?: (formData: FormData) => Promise<void>;
  screenshotHref?: string;
}) {
  const { content, claims, formAction } = props;
  const productHref = safeHref(props.productUrl);
  return (
    <main lang="en" className="mx-auto flex w-full max-w-3xl flex-col gap-8 px-5 py-10 sm:px-6 sm:py-14">
      {props.simulated ? (
        <p className="rounded-md border border-amber-500 bg-amber-50 px-3 py-2 text-sm text-amber-900">
          Sample page generated by a simulated model. Nothing here is a real product claim.
        </p>
      ) : null}
      <section className="flex flex-col items-start gap-4 border-b pb-7">
        <p className="text-sm font-semibold text-primary">
          {productHref ? (
            <a href={productHref} className="underline" rel="noreferrer noopener">
              {props.productName}
            </a>
          ) : (
            props.productName
          )}
        </p>
        <h1 className="text-4xl font-extrabold tracking-tight break-words sm:text-5xl">{content.headline}</h1>
        <p className="text-lg text-muted-foreground">{content.subheadline}</p>
        <CtaLink slug={props.slug} label={content.cta_label} enabled={!!formAction} />
      </section>

      {props.screenshotHref ? (
        <figure className="overflow-hidden rounded-lg border bg-muted">
          <Image src={props.screenshotHref} alt="Product screenshot" width={1000} height={650}
            className="h-auto max-h-[500px] w-full object-contain" unoptimized />
        </figure>
      ) : null}

      <section className="flex flex-col gap-2">
        <h2 className="text-xl font-semibold">Why teams try it</h2>
        <ul className="list-disc pl-5">
          {content.value_props.map((item) => (
            <li key={item}>{item}</li>
          ))}
        </ul>
      </section>

      <section className="flex flex-col gap-2">
        <h2 className="text-xl font-semibold">When it helps</h2>
        <ul className="list-disc pl-5">
          {content.scenarios.map((item) => (
            <li key={item}>{item}</li>
          ))}
        </ul>
      </section>

      {claims.length ? (
        <section className="flex flex-col gap-2">
          <h2 className="text-xl font-semibold">What we have heard</h2>
          <ul className="list-disc pl-5">
            {claims.map((claim) => (
              <li key={claim.text}>{claim.text}</li>
            ))}
          </ul>
        </section>
      ) : null}

      <section id="lead-form" className="flex scroll-mt-8 flex-col gap-4 rounded-xl border bg-card p-5 sm:p-6">
        <h2 className="text-xl font-semibold">{content.cta_label}</h2>
        {props.submitted ? (
          <p className="rounded-md border p-3" role="status">
            Thanks, we received your details and will be in touch.
          </p>
        ) : (
          <form action={formAction} className="flex flex-col gap-4">
            <div className="hidden" aria-hidden>
              <Label htmlFor="company_site">Company site</Label>
              <Input id="company_site" name="company_site" tabIndex={-1} autoComplete="off" />
            </div>
            <div className="flex flex-col gap-2">
              <Label htmlFor="email">Email</Label>
              <Input id="email" name="email" type="email" required maxLength={254} />
            </div>
            <div className="flex flex-col gap-2">
              <Label htmlFor="message">{content.form_prompt}</Label>
              <Textarea id="message" name="message" maxLength={2000} />
            </div>
            <Button type="submit" className="self-start" disabled={!formAction}>
              {content.cta_label}
            </Button>
          </form>
        )}
        <p className="text-sm text-muted-foreground">
          We only use your email to follow up about this product. To delete your details, contact{" "}
          {process.env.PRIVACY_CONTACT ?? "the product team"}.
        </p>
      </section>
    </main>
  );
}
